const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync('wwwroot/app.js', 'utf8');
const venues = [{name:'Hotel A & Spa',district:'George Town'}, {name:'Hotel B',district:'Butterworth'}];
const nodes = Object.fromEntries(['#maplinks','#venue-map','#map-name','#map-directions'].map(id=>[id,{}]));
const rows = venues.map((v,index)=>({dataset:{mapIndex:String(index)},handlers:{},classList:{toggle(name,value){this.active=value;}},button:{handlers:{},setAttribute(name,value){this[name]=value;},addEventListener(name,fn){this.handlers[name]=fn;}},querySelector(){return this.button;},addEventListener(name,fn){this.handlers[name]=fn;}}));
nodes['#maplinks'].querySelectorAll=()=>rows;
let callback;
const context = vm.createContext({venues,$:id=>nodes[id],esc:s=>s,link:()=>'',maps:v=>'https://maps.example/'+encodeURIComponent(v.name),setTimeout:fn=>{callback=fn;return 1;},clearTimeout:()=>{callback=null;}});
vm.runInContext(source.slice(source.indexOf('function initVenueMap()'),source.indexOf('function renderGiftOptions()')),context);
vm.runInContext('initVenueMap()',context);
assert.equal(nodes['#map-name'].textContent,venues[0].name);
assert.match(nodes['#venue-map'].src,/Hotel%20A%20%26%20Spa/);
assert.equal(rows[0].button['aria-pressed'],'true');
rows[1].handlers.pointerenter({pointerType:'mouse'});
assert.equal(nodes['#map-name'].textContent,venues[0].name);
callback();
assert.equal(nodes['#map-name'].textContent,venues[1].name);
assert.equal(rows[0].button['aria-pressed'],'false');
rows[0].handlers.pointerenter({pointerType:'mouse'}); rows[0].handlers.pointerleave(); assert.equal(callback,null);
rows[0].handlers.pointerenter({pointerType:'touch'}); assert.equal(callback,null);
rows[0].button.handlers.click(); assert.equal(nodes['#map-name'].textContent,venues[0].name);
rows[1].handlers.focusin(); assert.equal(nodes['#map-name'].textContent,venues[1].name);
assert.equal(nodes['#map-directions'].hidden,false);
console.log('PASS: Initial hotel, encoded query, hover delay/cancellation, touch, click, keyboard and active selection');
